/** The bundle the core is opened with. */
export interface ContentBundle {
  /** The digest the build computed and embedded. */
  hash: string;
  /** The manifest, as its own bytes. */
  manifest: string;
  /** Every listed file's bytes, in manifest order. */
  files: string[];
}

/** The manifest's shape, as this module reads it. */
interface Manifest {
  content_version: number;
  chapters: string[];
  forms: string[];
  pressures: string[];
}

/** The eight chapters, in the closed set's own order. */
const CHAPTERS: Record<string, string> = {
  the_pull: thePull,
  the_edge: theEdge,
  the_loop: theLoop,
  the_echo: theEcho,
  the_mesh: theMesh,
  the_break: theBreak,
  the_rewrite: theRewrite,
  the_quiet_edge: theQuietEdge,
};

const FORMS: Record<string, string> = {
  thread,
  ring,
  relay,
  vault,
  lens,
  knot,
  wake,
  chorus,
};

/** The six authored pressures, in the closed set's own order. */
const PRESSURES: Record<string, string> = {
  drain,
  noise,
  fracture,
  flood,
  interference,
  drift,
};

/** The manifest text exactly as it sits on disk, which is what is hashed. */
export const MANIFEST_TEXT = manifestText;

/** The digest the build embedded. */
export const CONTENT_HASH: string = generated.content_hash;

/**
 * The bundle, in manifest order. A manifest naming a file this build does not
 * carry is a defect in the build rather than a fault the core can answer, so it
 * throws here: the worker's fault path turns it into the one error envelope.
 */
export function contentBundle(): ContentBundle {
  const manifest = JSON.parse(manifestText) as Manifest;
  const listed: [string[], Record<string, string>][] = [
    [manifest.chapters, CHAPTERS],
    [manifest.forms, FORMS],
    [manifest.pressures, PRESSURES],
  ];
  const files: string[] = [];
  for (const [ids, held] of listed) {
    for (const id of ids) {
      const text = held[id];
      if (text === undefined) {
        throw new Error(`field_game content: the manifest lists ${id}, which is not bundled`);
      }
      files.push(text);
    }
  }
  return { hash: CONTENT_HASH, manifest: manifestText, files };
}
