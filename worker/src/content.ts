/**
 * The authored content, statically imported and handed to the core.
 *
 * `docs/field-framework/ARCHITECTURE.md` (Authored content) locks the layout
 * and the rule: all gameplay data is versioned JSON under `field_game/content/`,
 * statically imported into the worker bundle at build time and never fetched at
 * runtime, and `content_hash` is the SHA-256 over the concatenation of the
 * manifest bytes and every listed file's bytes in manifest order, computed by
 * the build and embedded.
 *
 * Each file is imported as its bytes rather than as parsed data, because the
 * bytes are what the hash is over: the core recomputes the digest across
 * exactly what it is handed and refuses the bundle when it disagrees with the
 * one the build embedded. That is what keeps a stale generated digest from
 * shipping quietly, and it is why nothing here re-serializes anything.
 *
 * The order the files are handed over in is the manifest's own — chapters, then
 * Forms, then pressures, each in its listed order — and it is taken from the
 * manifest at load rather than from the order of the imports below, so the two
 * cannot drift apart.
 *
 * `../build/content.json` is generated by `tools/content-build.mjs`, which the
 * build and the test setup both run.
 */

